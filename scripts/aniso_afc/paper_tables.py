#!/usr/bin/env python3
"""
Three tables of the paper from ParMooN's runs, in the layout of galerkit's make_report.py
(galerkit branch feature/anisotropic-afc), with the columns and rows the report tables of
report_extra.py did not have:

  aniso_layermesh_acc.tex  layer-adapted meshes (+ off), n = 128, eps = 1e-8: L2 error and maximal
                           error away from the layers for Galerkin, Kuzmin, MUAS (Examples 1, 2) and
                           the last column max u_h of Kuzmin for Example 3 (exact bound 1).
                           Fixed point runs (step 5); where the fixed point iteration did not
                           converge, an Anderson / Newton run with a smaller residual, if there is
                           one (galerkit: a Newton solve as fallback), as paper_figures.py.
  aniso_newton_reg.tex     Example 3, eps = 1e-8, n = 32 and 128, uniform / Shishkin "/" (+ off):
                           iterations and wall time of the fixed point iteration, Anderson acceleration
                           and Newton with regularized limiters and continuation (counted: all Newton
                           steps); not solved (Newton: not ended at sigma = 0) in \\mism{}.
  aniso_rotating.tex       Example 5, eps = 1e-5, n = 64: L2 error (r <= 1) and undershoot per mesh, for
                           the ten methods, + off and mu = 2 (BJK, Kuzmin, MUAS, SMUAS); solver as
                           rotating_figure.py (galerkit's rule); $^*$: not solved.

--run computes the runs of aniso_newton_reg (run_study.py; finished runs are skipped); the runs of
the other two tables are those of steps 5 and 10 of the run guide.

Usage (from the build directory):
  python3 ../ParMooN-2026/scripts/aniso_afc/paper_tables.py [--outdir cd_aniso] [--dest paper_results]
  python3 ../ParMooN-2026/scripts/aniso_afc/paper_tables.py --run --jobs 4      # with the runs of newton_reg
"""
import argparse
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import paper_figures as PF  # noqa: E402
import rotating_figure as RF  # noqa: E402
from run_study import UNSOLVED_NOTE  # noqa: E402

HEAD = "% generated by scripts/aniso_afc/paper_tables.py (ParMooN), layout of galerkit's make_report.py\n"
NAME = PF.NAME
AFC = PF.AFC
NC_M = ("bjk", "kuzmin_edge", "muas", "smuas", "bbk", "fbbk", "sbbk")       # no MC (no regularization)
LMESH = [("uniform", False), ("shishkin_r", False), ("bakhvalov_shishkin", False), ("bakhvalov", False),
         ("duran", False), ("shishkin_r", True), ("bakhvalov_shishkin", True), ("bakhvalov", True)]
LMESH_TEX = {"uniform": "uniform", "shishkin_r": "Shishkin", "bakhvalov_shishkin": "Bakhvalov--Shishkin",
             "bakhvalov": "Bakhvalov", "duran": "Dur\\'an--Lombardi"}
NR_N = (32, 128)
NR_ROWS = (("uniform", "plain"), ("shishkin_r", "plain"), ("shishkin_r", "loff"))
NR_SOLVERS = (("fixed_point", "fp rhs"), ("fp_anderson", "Anderson"), ("newton_cont", "Newton, reg."))


def sci(x, d=1):
    if x is None or not np.isfinite(x):
        return "--"
    if x == 0:
        return "0"
    m, e = f"{x:.{d}e}".split("e")
    return f"${m}\\mathrm{{e}}{{{int(e)}}}$"


def mism(s):
    return f"\\mism{{{s}}}"


def accuracy_run(R, ex, eps, mesh, n, method, variant):
    """the fixed point run; if it did not converge, an Anderson / Newton run with a smaller residual"""
    r = R.get(ex, eps, mesh, n, method, variant)
    if r is None or method in PF.LINEAR or r.get("converged"):
        return r
    best, best_res = r, r.get("residual") if r.get("residual") is not None else np.inf
    for s in ("fp_anderson_safe", "newton_cont"):
        q = R.get(ex, eps, mesh, n, method, variant, s)
        x = None if q is None else PF.residual0(q)
        if x is not None and np.isfinite(x) and x < best_res:
            best, best_res = q, x
    return best


# ----------------------------------------------------------------------------- the tables
def table_layermesh_acc(R, n=128):
    cases = [(1, 1e-8), (2, 1e-8)]
    if not any(R.get(ex, eps, m, n, s, "plain", "linear" if s == "galerkin" else "fixed_point")
               for ex, eps in cases for m, _ in LMESH for s in ("galerkin", "kuzmin_edge", "muas")):
        return None
    body = []
    for m, lo in LMESH:
        var = "loff" if lo else "plain"
        cells = [LMESH_TEX[m] + (" + off" if lo else "")]
        for ex, eps in cases:
            for s in ("galerkin", "kuzmin_edge", "muas"):
                if lo and s == "galerkin":
                    cells += ["--", "--"]
                    continue
                r = (R.get(ex, eps, m, n, s, "plain", "linear") if s == "galerkin"
                     else accuracy_run(R, ex, eps, m, n, s, var))
                cells += ["--", "--"] if r is None else [sci(r.get("L2")), sci(r.get("Linf_away"))]
        r = accuracy_run(R, 3, 1e-8, m, n, "kuzmin_edge", var)
        cells.append("--" if r is None or r.get("u_max") is None or not np.isfinite(r["u_max"])
                     else f"{r['u_max']:.3f}")
        body.append(" & ".join(cells) + r" \\")
    return (HEAD + "\\begin{table}[!htbp]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}\n"
            f"\\caption{{Accuracy on the layer-adapted meshes, $n={n}$, $\\varepsilon=10^{{-8}}$: $L^2$ error and maximal "
            "nodal error away from the layers for Galerkin, Kuzmin and MUAS; last column: $\\max u_h$ of Kuzmin for "
            "\\texttt{parabolic\\_layers} (exact bound 1).}\\label{tab:lm-acc}\n"
            "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l rrrrrr rrrrrr r}\n\\toprule\n"
            " & \\multicolumn{6}{c}{\\texttt{exp\\_layer}} & \\multicolumn{6}{c}{\\texttt{boundary\\_layers}} & parab.\\\\\n"
            " & \\multicolumn{2}{c}{Galerkin} & \\multicolumn{2}{c}{Kuzmin} & \\multicolumn{2}{c}{MUAS}"
            " & \\multicolumn{2}{c}{Galerkin} & \\multicolumn{2}{c}{Kuzmin} & \\multicolumn{2}{c}{MUAS} & Kuzmin\\\\\n"
            "mesh" + " & $L^2$ & away" * 6 + " & $\\max u_h$\\\\\n\\midrule\n" + "\n".join(body)
            + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")


def _solved_nr(r):
    """galerkit: fixed point / Anderson converged; Newton with continuation ended at sigma = 0 ('polished';
    runs without that record: the converged flag)"""
    if not r.get("converged"):
        return False
    if r.get("solver") == "newton_cont" and r.get("polished") is False:
        return False
    return True


def table_newton_reg(R):
    if not any(R.get(3, 1e-8, m, n, s, v, sv) for n in NR_N for m, v in NR_ROWS for s in NC_M
               for sv, _ in NR_SOLVERS):
        return None
    mt = {"uniform": "uniform", "shishkin_r": "Shishkin /"}
    body = []
    for n in NR_N:
        body.append(f"\\multicolumn{{8}}{{l}}{{$n={n}$}}\\\\")
        for m, v in NR_ROWS:
            for sv, name in NR_SOLVERS:
                cells = [mt[m] + (" + off" if v == "loff" else "") + ", " + name]
                for s in NC_M:
                    r = R.get(3, 1e-8, m, n, s, v, sv)
                    if r is None or r.get("iterations") is None:
                        cells.append("--")
                    elif _solved_nr(r):
                        t = r.get("wall_time")
                        cells.append(f"{r['iterations']}" + ("" if t is None else f" ({t:.0f}\\,s)"))
                    else:
                        cells.append(mism(r["iterations"]))
                body.append(" & ".join(cells) + r" \\")
        body.append("\\midrule")
    return (HEAD + "\\begin{table}[!htbp]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}\n"
            "\\caption{\\texttt{parabolic\\_layers}, $\\varepsilon=10^{-8}$: iterations (and wall time of the run) "
            "of the fixed point rhs, its Anderson acceleration, and Newton's method with regularized limiters "
            "and continuation $\\sigma=10^{-1},\\dots,10^{-6}$ followed by Newton on the original scheme (counted: all "
            "Newton steps); in \\mism{colour}: the original scheme is not solved.}\\label{tab:nreg}\n"
            "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l rrrrrrr}\n\\toprule\nmesh, solver & "
            + " & ".join(NAME[s] for s in NC_M) + "\\\\\n\\midrule\n"
            + "\n".join(body[:-1]) + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")


def table_rotating(outdir, n=64, eps=1e-5):
    recs = RF.records(outdir)
    if not recs:
        return None
    ks = RF.MESHES
    kt = {"uniform": "uniform", "polar": "polar", "polar_layer": "polar, layer-adapted",
          "tensor_layer": "tensor, layer-refined"}
    body = []
    for st in RF.ALL:
        for var in ("plain", "loff", "mu2"):
            if (var != "plain" and st in RF.LINEAR) or (var == "mu2" and st not in RF.RELAXED):
                continue
            cells = [NAME[st] + {"plain": "", "loff": " + off", "mu2": ", $\\mu=2$"}[var]]
            for k in ks:
                r = None if (var == "loff" and k not in RF.OFF_MESHES) else \
                    RF.choose(recs, eps, k, n, st, var, RF.SOLVERS)
                if r is None or r.get("L2_r1_lumped") is None:
                    cells += ["--", "--"]
                    continue
                star = "" if RF.solved(r) else "$^*$"
                u = r.get("undershoot") or 0.0
                cells += [sci(r["L2_r1_lumped"]) + star, sci(u) if u > 1e-8 else "0"]
            body.append(" & ".join(cells) + r" \\")
    return (HEAD + "\\begin{table}[!htbp]\n\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n"
            f"\\caption{{\\texttt{{rotating\\_profile}}, $\\varepsilon=10^{{-5}}$, $n={n}$: $L^2$ error ($r\\le1$) "
            "against the radial reference and undershoot $-\\min u_h$; + off: limiter switched off "
            "along the layers (aspect threshold 3); $\\mu=2$: relaxed limiter; $^*$: nonlinear problem not solved, "
            + UNSOLVED_NOTE + "."
            "}\\label{tab:rotating}\n"
            "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l rr rr rr rr}\n\\toprule\n & "
            + " & ".join(f"\\multicolumn{{2}}{{c}}{{{kt[k]}}}" for k in ks) + "\\\\\n"
            "method" + " & $L^2$ & under." * 4 + "\\\\\n\\midrule\n" + "\n".join(body)
            + "\n\\bottomrule\n\\end{tabular}}\n\\end{table}\n")


TABLES = ("aniso_layermesh_acc.tex", "aniso_newton_reg.tex", "aniso_rotating.tex")


def make_all(outdir, dest, quiet=False):
    """the three tables from the runs in outdir into dest; returns the files written"""
    R = PF.Runs(outdir)
    out = []
    for name, txt in (("aniso_layermesh_acc.tex", table_layermesh_acc(R)),
                      ("aniso_newton_reg.tex", table_newton_reg(R)),
                      ("aniso_rotating.tex", table_rotating(outdir))):
        if txt is None:
            if not quiet:
                print(f"{name}: no runs")
            continue
        os.makedirs(dest, exist_ok=True)
        f = os.path.join(dest, name)
        open(f, "w").write(txt)
        out.append(f)
        if not quiet:
            print(f"wrote {f}")
    return out


def compute_runs(args):
    """the runs of aniso_newton_reg (Example 3, n = 32, 128)"""
    study = os.path.join(HERE, "run_study.py")
    for sv, _ in NR_SOLVERS:
        for meshes, var in ((("uniform", "shishkin_r"), "plain"), (("shishkin_r",), "loff")):
            cmd = [sys.executable, study, "--exe", args.exe, "--outdir", args.outdir, "--jobs", str(args.jobs),
                   "--cases", "3:1e-8", "--n", *map(str, NR_N), "--meshes", *meshes, "--methods", *NC_M,
                   "--variants", var, "--solver", sv]
            print(f"\n[{sv}, {var}] " + " ".join(meshes), flush=True)
            subprocess.run(cmd, check=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--outdir", default="cd_aniso", help="the runs of run_study.py (default cd_aniso)")
    ap.add_argument("--dest", default="paper_results", help="folder of the tables (default paper_results)")
    ap.add_argument("--run", action="store_true", help="compute the runs of aniso_newton_reg first")
    ap.add_argument("--exe", default="./parMooN_cd2d_afc_SEQUENTIAL")
    ap.add_argument("--jobs", type=int, default=1)
    args = ap.parse_args()
    if args.run:
        compute_runs(args)
    make_all(args.outdir, args.dest)


if __name__ == "__main__":
    main()
