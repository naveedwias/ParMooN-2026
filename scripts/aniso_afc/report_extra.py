"""
Further tables of the anisotropic AFC study (formats of the paper's tables
aniso_roff, aniso_layermesh_acc / _it, aniso_anderson, aniso_newton_all,
aniso_interior, aniso_rotating), from the run records of run_study.py. Every
table is written only if the records it needs exist:

  <pre>_<study>_switch_<roff|loff>.tex  L2 (or the maximal error) and iterations,
                                     stabilization everywhere / switched off (two largest n)
  <pre>_<study>_layermesh_acc.tex    L2 and maximal error away from the layers on the
                                     layer-adapted meshes (+ off), Galerkin, Kuzmin, MUAS
  <pre>_<study>_layermesh_it.tex     iterations on the layer-adapted meshes (+ off)
  <pre>_<study>_solvers.tex          iterations of every solver (fixed point, Anderson,
                                     Anderson with safeguard, Newton, Newton continuation)
  <pre>_<study>_solved.tex           solved runs over n: fixed point / Newton continuation
  <pre>_<study>_ex4.tex, _ex5.tex    Examples 4 and 5 per mesh (+ off)
"""
import os

from run_study import LABEL, LINEAR, MESH_LABEL, get, load, mism, tex_num

SOLVER_LABEL = {"fixed_point": "fixed point", "fp_anderson": "Anderson", "fp_anderson_safe": "Anderson, safeg.",
                "newton": "Newton", "newton_cont": "Newton, cont."}
LAYER_MESHES = ("uniform", "shishkin_r", "bakhvalov_shishkin", "bakhvalov", "duran")


def _write(outdir, name, lines):
    f = os.path.join(outdir, name)
    open(f, "w").write("% generated by scripts/aniso_afc/report_extra.py (ParMooN)\n" + "\n".join(lines) + "\n")
    print(f"wrote {f}")


def _err(r, key):
    if r is None or r.get(key) is None:
        return "--"
    return tex_num(r[key]) + ("" if r.get("converged", True) else "$^*$")


def _it(r):
    if r is None or r.get("iterations") is None:
        return "--"
    return str(r["iterations"]) if r.get("converged") else mism(r["iterations"])


def _keys(ex):
    return {1: ("L2", "Linf_away"), 2: ("L2", "Linf_away"), 3: (None, None), 4: ("L2_away_lumped", "Linf_mid"),
            5: ("L2_r1_lumped", "Linf_r1")}[ex]


def report_extra(outdir, study, cases, methods, ns):
    R = load(outdir)
    # only the runs of the requested cases (other examples' runs are in the same folder)
    R = [r for r in R if (r.get("example"), r.get("eps")) in {(ex, eps) for ex, eps in cases}]
    if not R:
        print("report_extra: no runs for the cases " + ", ".join(f"{ex}:{eps:g}" for ex, eps in cases)
              + " - run them first")
        return
    pre = "cd_aniso"
    nmax = max(ns)
    n2 = sorted(ns)[-2:]
    afc = [m for m in methods if m not in LINEAR]
    # switches
    for var, what in (("roff", "switched off on the edges with $|\\bb||E|/(2\\varepsilon)\\le1$"),
                      ("loff", "switched off along the layers")):
        if not any(r.get("variant") == var for r in R):
            continue
        lines = []
        for ex, eps in cases:
            l2 = _keys(ex)[0] or "Linf_nodes"
            ms = [m for m in ("shishkin_r", "shishkin_x") if any(r["mesh"] == m and r["example"] == ex and
                                                                  r["eps"] == eps and r.get("variant") == var
                                                                  for r in R)]
            if not ms:
                continue
            lines += ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}",
                      f"\\caption{{Example~{ex}, $\\varepsilon={eps:g}$: error and iterations with the stabilization "
                      f"everywhere / {what}; $^*$: not converged.}}",
                      "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l " + " ".join(["rr"] * (len(ms) * len(n2))) + "}",
                      "\\toprule",
                      " & " + " & ".join(f"\\multicolumn{{{2 * len(n2)}}}{{c}}{{{MESH_LABEL[m]}}}" for m in ms) + "\\\\",
                      " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{$n={n}$}}" for _ in ms for n in n2) + "\\\\",
                      "method & " + " & ".join(["error & it."] * (len(ms) * len(n2))) + "\\\\", "\\midrule"]
            for meth in afc:
                cells = []
                for m in ms:
                    for n in n2:
                        a = get(R, example=ex, eps=eps, mesh=m, n=n, method=meth, variant="plain", solver="fixed_point")
                        b = get(R, example=ex, eps=eps, mesh=m, n=n, method=meth, variant=var, solver="fixed_point")
                        cells += [f"{_err(a, l2)} / {_err(b, l2)}", f"{_it(a)} / {_it(b)}"]
                lines.append(f"{LABEL[meth]} & " + " & ".join(cells) + " \\\\")
            lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
        if lines:
            _write(outdir, f"{pre}_{study}_switch_{var}.tex", lines)
    # layer-adapted meshes
    lm = [m for m in LAYER_MESHES if any(r["mesh"] == m for r in R)]
    if any(m in ("bakhvalov_shishkin", "bakhvalov", "duran") for m in lm):
        rows = [(m, v) for m in lm for v in ("plain", "loff") if m != "uniform" or v == "plain"]
        acc_m = [m for m in ("galerkin", "kuzmin_edge", "muas") if m in methods]
        ex12 = [(ex, eps) for ex, eps in cases if ex in (1, 2)]
        lines = ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}",
                 f"\\caption{{Accuracy on the layer-adapted meshes, $n={nmax}$: $L^2$ error and maximal nodal error "
                 "away from the layers; + off: stabilization switched off along the layers.}",
                 "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l " + " ".join(["rr" * len(acc_m)] * len(ex12)) + "}",
                 "\\toprule",
                 " & " + " & ".join(f"\\multicolumn{{{2 * len(acc_m)}}}{{c}}{{Example~{ex}, $\\varepsilon={eps:g}$}}"
                                    for ex, eps in ex12) + "\\\\",
                 " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{LABEL[m]}}}" for _ in ex12 for m in acc_m) + "\\\\",
                 "mesh & " + " & ".join(["$L^2$ & max"] * (len(ex12) * len(acc_m))) + "\\\\", "\\midrule"]
        for m, v in rows:
            cells = []
            for ex, eps in ex12:
                for meth in acc_m:
                    r = get(R, example=ex, eps=eps, mesh=m, n=nmax, method=meth, variant=v,
                            solver="linear" if meth in LINEAR else "fixed_point")
                    if meth in LINEAR and v != "plain":
                        cells += ["--", "--"]
                    else:
                        cells += [_err(r, "L2"), _err(r, "Linf_away")]
            lines.append(f"{MESH_LABEL[m]}{' + off' if v == 'loff' else ''} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
        _write(outdir, f"{pre}_{study}_layermesh_acc.tex", lines)
        lines = ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
                 f"\\caption{{Iterations of the fixed point iteration on the layer-adapted meshes, $n={nmax}$; "
                 "\\mism{colour}: not converged; + off: switched off along the layers.}",
                 "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l " + "r" * len(afc) + "}", "\\toprule",
                 "mesh & " + " & ".join(LABEL[m] for m in afc) + "\\\\", "\\midrule"]
        for ex, eps in cases:
            lines.append(f"\\multicolumn{{{len(afc) + 1}}}{{l}}{{Example~{ex}, $\\varepsilon={eps:g}$}}\\\\")
            for m, v in rows:
                cells = [_it(get(R, example=ex, eps=eps, mesh=m, n=nmax, method=meth, variant=v,
                                 solver="fixed_point")) for meth in afc]
                lines.append(f"{MESH_LABEL[m]}{' + off' if v == 'loff' else ''} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
        _write(outdir, f"{pre}_{study}_layermesh_it.tex", lines)
    # solvers
    solvers = [s for s in SOLVER_LABEL if any(r.get("solver") == s for r in R)]
    if len(solvers) > 1:
        lines = ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
                 f"\\caption{{Iterations at $n={nmax}$ of the nonlinear solvers (Anderson: depth 10, restart after 200 "
                 "iterations without halving the residual; safeg.: non-monotone residual safeguard, window 10; "
                 "Newton, cont.: regularized limiters, $\\sigma=10^{-1},\\dots,10^{-6}$, then $\\sigma=0$); "
                 "\\mism{colour}: not converged.}",
                 "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l " + "r" * len(afc) + "}", "\\toprule",
                 "mesh, solver & " + " & ".join(LABEL[m] for m in afc) + "\\\\", "\\midrule"]
        for ex, eps in cases:
            lines.append(f"\\multicolumn{{{len(afc) + 1}}}{{l}}{{Example~{ex}, $\\varepsilon={eps:g}$}}\\\\")
            for m in ("uniform", "shishkin_r", "shishkin_x"):
                for sv in solvers:
                    if not any(r["example"] == ex and r["eps"] == eps and r["mesh"] == m and r.get("solver") == sv
                               for r in R):
                        continue
                    cells = [_it(get(R, example=ex, eps=eps, mesh=m, n=nmax, method=meth, variant="plain",
                                     solver=sv)) for meth in afc]
                    lines.append(f"{MESH_LABEL[m]}, {SOLVER_LABEL[sv]} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
        _write(outdir, f"{pre}_{study}_solvers.tex", lines)
    # solved runs: fixed point / Newton continuation
    if any(r.get("solver") == "newton_cont" for r in R):
        nc = [m for m in afc if m != "mc"]
        lines = ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
                 f"\\caption{{Solved runs (of $n={','.join(map(str, ns))}$): fixed point iteration / Newton with "
                 "regularized limiters and continuation (finite-difference Jacobian); + off: switched off along "
                 "the layers.}", "\\begin{tabular}{l " + "r" * len(nc) + "}", "\\toprule",
                 "mesh & " + " & ".join(LABEL[m] for m in nc) + "\\\\", "\\midrule"]
        for ex, eps in cases:
            lines.append(f"\\multicolumn{{{len(nc) + 1}}}{{l}}{{Example~{ex}, $\\varepsilon={eps:g}$}}\\\\")
            for m in sorted({r["mesh"] for r in R if r["example"] == ex and r["eps"] == eps},
                            key=lambda x: list(MESH_LABEL).index(x) if x in MESH_LABEL else 99):
                for v in ("plain", "loff"):
                    if not any(r["example"] == ex and r["eps"] == eps and r["mesh"] == m and r.get("variant") == v
                               and r.get("solver") == "newton_cont" for r in R):
                        continue
                    cells = []
                    for meth in nc:
                        cnt = []
                        for sv in ("fixed_point", "newton_cont"):
                            cnt.append(sum(1 for n in ns if (get(R, example=ex, eps=eps, mesh=m, n=n, method=meth,
                                                                 variant=v, solver=sv) or {}).get("converged")))
                        cells.append(f"{cnt[0]}/{cnt[1]}")
                    lines.append(f"{MESH_LABEL[m]}{' + off' if v == 'loff' else ''} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
        _write(outdir, f"{pre}_{study}_solved.tex", lines)
    # Examples 4 and 5: per mesh, + off; the best solver: Newton continuation, else Anderson, else fixed point
    for ex, eps in cases:
        if ex not in (4, 5):
            continue
        if not any(r["example"] == ex and r["eps"] == eps for r in R):
            print(f"report_extra: no runs for Example {ex}, eps = {eps:g}")
            continue
        ms = [m for m in (("uniform", "shishkin_r", "bakhvalov_shishkin", "bakhvalov") if ex == 4
                          else ("uniform", "polar", "polar_layer", "tensor_layer"))
              if any(r["example"] == ex and r["mesh"] == m for r in R)]
        n = max(r["n"] for r in R if r["example"] == ex)
        l2k, mk = _keys(ex)
        cols = (("max", mk), ("$L^2$", l2k), ("$\\max u_h$", "u_max")) if ex == 4 else \
            (("$L^2$", l2k), ("under.", "undershoot"))
        lines = ["\\begin{table}[!htbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{2.5pt}",
                 f"\\caption{{Example~{ex}, $\\varepsilon={eps:g}$, $n={n}$" +
                 (": maximal nodal error for $0.1\\le x\\le1-\\tau_x$, discrete (lumped) $L^2$ error for "
                  "$x\\le1-\\tau_x$ against the asymptotic reference, and $\\max u_h$"
                  if ex == 4 else ": discrete (lumped) $L^2$ error for $r\\le1$ against the radial reference and "
                                  "the undershoot $-\\min u_h$") +
                 "; + off: switched off along the layers; $^*$: not converged.}",
                 "\\resizebox{\\textwidth}{!}{\\begin{tabular}{l " + " ".join(["r" * len(cols)] * len(ms)) + "}",
                 "\\toprule", " & " + " & ".join(f"\\multicolumn{{{len(cols)}}}{{c}}{{{MESH_LABEL[m]}}}"
                                                  for m in ms) + "\\\\",
                 "method & " + " & ".join(c for _ in ms for c, _k in cols) + "\\\\", "\\midrule"]
        for meth in methods:
            for v in (("plain",) if meth in LINEAR else ("plain", "loff")):
                cells = []
                for m in ms:
                    r = None
                    for sv in (("linear",) if meth in LINEAR else ("newton_cont", "fp_anderson_safe", "fixed_point")):
                        r = get(R, example=ex, eps=eps, mesh=m, n=n, method=meth, variant=v, solver=sv)
                        if r is not None and r.get("converged", True):
                            break
                    for _c, k in cols:
                        if r is None or r.get(k) is None:
                            cells.append("--")
                        elif k == "u_max":
                            cells.append(f"{r[k]:.3f}")
                        else:
                            cells.append(_err(r, k) if k != "undershoot" else tex_num(r[k]))
                lines.append(f"{LABEL[meth]}{' + off' if v == 'loff' else ''} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
        _write(outdir, f"{pre}_{study}_ex{ex}.tex", lines)
